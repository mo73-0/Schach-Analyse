// Generates src/openings.js from the Lichess opening database (CC0):
//   git clone --depth 1 https://github.com/lichess-org/chess-openings /tmp/chess-openings
//   node src/gen_openings.js /tmp/chess-openings
// Every position reached by a named opening line counts as "book" (theory).
const fs = require('fs'), path = require('path');
const C = require('./chess.js');
const dir = process.argv[2];
if (!dir) { console.error('Pfad zu chess-openings fehlt'); process.exit(1); }
const key = fen => fen.split(' ').slice(0, 4).join(' ');
const hash = s => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return (h >>> 0).toString(36); };
const book = new Set(), names = new Map();
let lines = 0, bad = 0;
for (const f of ['a', 'b', 'c', 'd', 'e']) {
  for (const row of fs.readFileSync(path.join(dir, f + '.tsv'), 'utf8').split('\n').slice(1)) {
    if (!row.trim()) continue;
    const [eco, name, pgn] = row.split('\t');
    try {
      const g = C.parsePgn(pgn);
      for (const m of g.moves) book.add(hash(key(m.fenAfter)));
      names.set(hash(key(g.moves[g.moves.length - 1].fenAfter)), eco + ' ' + name);
      lines++;
    } catch (e) { bad++; }
  }
}
const list = [...new Set(names.values())];
const idx = new Map(list.map((n, i) => [n, i]));
const out = `// Generated by src/gen_openings.js from lichess-org/chess-openings (CC0 1.0). Do not edit.
const OPENINGS = { book: ${JSON.stringify([...book].join(','))}, pos: ${JSON.stringify([...names].map(([h, n]) => h + ':' + idx.get(n).toString(36)).join(','))}, names: ${JSON.stringify(list)} };
`;
fs.writeFileSync(path.join(__dirname, 'openings.js'), out);
console.log('Linien', lines, 'Fehler', bad, 'Theoriestellungen', book.size, 'Namen', list.length, 'Größe', out.length);
